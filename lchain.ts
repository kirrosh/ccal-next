import { PromptTemplate } from "@langchain/core/prompts";
import { ChatGoogleGenerativeAI } from "@langchain/google-genai";
import { mealPlan } from "./schemas/meal";

const llm = new ChatGoogleGenerativeAI({
    model: "gemini-2.0-flash-001",
    maxOutputTokens: 8192,
    temperature: 0.7,
    topP: 0.95,
    apiKey: process.env.GOOGLE_API_KEY,
  });
  

const prompt = PromptTemplate.fromTemplate(
    `
    Ты - опытный шеф-повар и диетолог. Составь детальный рацион питания на неделю на русском языке с рецептами, которые можно легко приготовить дома или приобрести в кафе/кулинарии.
    
Параметры:
- people_count: {people_count} (количество человек)
- goal: {goal} (weight_loss = похудение, muscle_gain = набор массы, maintenance = поддержание формы)
- preferences: {preferences} (предпочтения в еде)
- allergies: {allergies} (исключенные продукты/аллергены)
- region: {region} (используй продукты, доступные в этом регионе)
- current_date: {current_date} (используй для определения сезона и сезонных продуктов)
- available_products: {available_products} (постарайся максимально использовать продукты, которые уже есть)

Требования к рациону:
1. ОБЯЗАТЕЛЬНО составь МИНИМУМ 3 варианта завтраков
2. ОБЯЗАТЕЛЬНО составь МИНИМУМ 4 варианта обедов
3. ОБЯЗАТЕЛЬНО составь МИНИМУМ 4 варианта ужинов
4. ОБЯЗАТЕЛЬНО составь МИНИМУМ 3 варианта перекусов

ОБЯЗАТЕЛЬНО: Включи в рацион готовые блюда из кафе или кулинарии:
- Включи НЕ МЕНЕЕ 2 БЛЮД КАЖДОЙ КАТЕГОРИИ (завтрак, обед, ужин, перекус), которые можно приобрести в кафе/кулинарии (например, "Винегрет из кулинарии", "Куриная котлета с гарниром из картофеля", "Овощной салат из кафе")
- Для таких блюд все равно укажи примерный состав ингредиентов и их количество, как для обычных блюд
- Укажи для таких блюд поле dishType = "readymade"
- Для блюд домашнего приготовления устанавливай поле dishType = "homemade"

КРАЙНЕ ВАЖНО О НАЗВАНИЯХ ИНГРЕДИЕНТОВ:
- Для блюд, которые готовятся дома, НИКОГДА не используй в качестве ингредиента общие названия готовых блюд вроде "овощной салат", "овощное рагу", "запеченная рыба"
- Вместо "овощной салат" укажи конкретные овощи: "огурец", "помидор", "перец", "лук"
- Вместо "овощное рагу" укажи отдельно каждый овощ: "картофель", "морковь", "баклажан", "лук", "перец"
- Вместо "запеченная рыба" укажи конкретный вид рыбы: "треска", "лосось", "минтай"
- Каждый ингредиент должен быть конкретным, сырым (не приготовленным) продуктом
- Однако для готовых блюд из кафе/кулинарии (dishType = "readymade") всё равно предоставь приблизительный список ингредиентов с их количеством

ВАЖНО О РЕЦЕПТАХ И ИНГРЕДИЕНТАХ:
- Каждое блюдо должно иметь конкретное, понятное название (например, "Овсяная каша с медом и яблоками" вместо просто "Овсянка")
- Для каждого блюда необходимо указать ДЕТАЛЬНЫЙ список ингредиентов, из которых оно готовится
- Каждый ингредиент должен иметь ЧЕТКО указанное НАЗВАНИЕ, КОЛИЧЕСТВО и ЕДИНИЦУ ИЗМЕРЕНИЯ
- Единицы измерения должны быть стандартными: граммы (г), миллилитры (мл), штуки (шт), столовые ложки (ст.л.), чайные ложки (ч.л.)
- НЕ используй обобщенные названия ингредиентов типа "салат", "суп", "рассольник" - вместо этого указывай конкретные продукты
- ПРИОРИТЕТНО используй продукты, которые уже есть в наличии у пользователя
- Учитывай СЕЗОННОСТЬ продуктов на основе текущей даты ({current_date})
- Все ингредиенты должны быть доступными в обычных магазинах
- Блюда должны быть разнообразными по составу и способу приготовления

Для КАЖДОГО блюда необходимо указать:
- Конкретное название блюда
- Тип блюда (dishType): "homemade" для приготовленных дома или "readymade" для готовых из кафе/кулинарии
- Структурированный список ингредиентов с отдельными полями: 
  * название продукта
  * количество (числовое значение)
  * единица измерения
- Нутриентный состав: калории, белки, жиры и углеводы (числовые значения в граммах)

ПРИМЕРЫ НЕПРАВИЛЬНЫХ ИНГРЕДИЕНТОВ, КОТОРЫЕ НЕЛЬЗЯ ИСПОЛЬЗОВАТЬ (кроме готовых блюд из кафе/кулинарии):
- "овощной салат" (вместо этого укажи конкретные овощи)
- "овощное рагу" (вместо этого перечисли все овощи по отдельности)
- "запеченная рыба" (укажи вид рыбы)
- "мясной соус" (укажи вид мяса и другие компоненты соуса)
- "фруктовый десерт" (перечисли конкретные фрукты)

ПРИМЕРЫ ПРАВИЛЬНЫХ ИНГРЕДИЕНТОВ, КОТОРЫЕ НУЖНО ИСПОЛЬЗОВАТЬ:
- "огурец свежий"
- "помидор"
- "куриное филе"
- "лосось"
- "картофель"
- "молоко 2,5%"
- "йогурт натуральный"
- "масло оливковое"

ПРИМЕРЫ ГОТОВЫХ БЛЮД ИЗ КАФЕ/КУЛИНАРИИ:
- "Винегрет из кулинарии" с dishType = "readymade"
- "Куриная котлета с гарниром из картофеля" с dishType = "readymade"
- "Овощной салат из кафе" с dishType = "readymade"
- "Борщ домашний из кулинарии" с dishType = "readymade"

ОЧЕНЬ ВАЖНО: Ты ДОЛЖЕН заполнить все разделы меню нужным количеством блюд (завтраки, обеды, ужины, перекусы).
В КАЖДОЙ категории должно быть НЕ МЕНЕЕ 2 ГОТОВЫХ БЛЮД (dishType = "readymade").
Если не заполнить все разделы нужным количеством блюд - задача будет считаться НЕВЫПОЛНЕННОЙ.

Примеры правильно структурированных ингредиентов:
1. name: "овсяные хлопья", amount: 70, unit: "г"
2. name: "куриное филе", amount: 200, unit: "г"
3. name: "оливковое масло", amount: 2, unit: "ст.л."
4. name: "яйцо", amount: 2, unit: "шт"
5. name: "молоко 1.5%", amount: 200, unit: "мл"

Для каждого блюда указывай минимум 2-6 ингредиентов. Не пропускай ни одного раздела, включая завтраки, обеды, ужины и перекусы!
    `
  );

const structuredLlm = llm.withStructuredOutput(mealPlan);

const chain = prompt.pipe(structuredLlm);
  

const completion = await chain.invoke({
    "people_count": 2,
    "goal": "weight_loss",
    "preferences": ["мясо"],
    "allergies": ["орехи"],
    "region": "Россия",
    "current_date": new Date().toISOString().split('T')[0], // Текущая дата в формате YYYY-MM-DD
    "available_products": ["куриное филе", "яйца", "овсянка", "гречка", "рис", "картофель", "морковь", "лук"]
  });

console.log(JSON.stringify(completion, null, 2));
